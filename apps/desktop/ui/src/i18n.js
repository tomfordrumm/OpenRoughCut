const dictionaries = { en, ru };

function systemLocale() {
  const languages = typeof navigator === "undefined" ? [] : navigator.languages ?? [navigator.language];
  return languages.some((code) => /^ru\b/i.test(code ?? "")) ? "ru" : "en";
}

function storedPreference() {
  try { return window.localStorage.getItem(STORAGE_KEY) ?? "system"; } catch { return "system"; }
}

let preference = typeof window === "undefined" ? "system" : storedPreference();
let locale = preference === "system" ? systemLocale() : preference;

export const localePreference = () => preference;
export const currentLocale = () => locale;

/** Pass "system", "en" or "ru". */
export function setLocalePreference(next) {
  preference = ["en", "ru"].includes(next) ? next : "system";
  locale = preference === "system" ? systemLocale() : preference;
  try { window.localStorage.setItem(STORAGE_KEY, preference); } catch {}
  document.documentElement.lang = locale;
  return locale;
}

export function t(key, vars) {
  const value = dictionaries[locale][key] ?? en[key] ?? key;
  return typeof value === "function" ? value(vars ?? {}) : value;
}

if (typeof document !== "undefined") document.documentElement.lang = locale;
